/** A purchasable furniture product. Dimensions are in meters. */
export interface FurnitureProduct {
  id: string;
  name: string;
  category: FurnitureCategory;
  /** Catalog price in USD. */
  price: number;
  /** Footprint along the room x-axis, meters. */
  width: number;
  /** Footprint along the room z-axis, meters. */
  depth: number;
  /** Height above the floor, meters. */
  height: number;
  styleTags: string[];
  colors: string[];
  material: string;
  stock: number;
  /** Default rotation in degrees (0 = width along x); omitted means 0. */
  defaultRotation?: number;
  /** CSS background gradient used for the catalog thumbnail. */
  thumbnailGradient?: string;
}

/** A placed furniture instance in the room. */
export interface PlacedFurniture {
  instanceId: string;
  productId: string;
  position: { x: number; y: number; z: number };
  /** Rotation in degrees. */
  rotation: number;
  locked: boolean;
  /** Existing items never count toward the new budget, regardless of price. */
  source: 'existing' | 'marketplace';
}

